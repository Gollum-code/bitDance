export function formatStrategyOptionLabel(
  strategyId: string,
  className?: string,
  locked?: boolean,
  archetype?: string,
): string {
  const id = (strategyId || '').trim()
  const key = id.length <= 2 ? id.padStart(2, '0') : id
  const title = STRATEGY_DISPLAY_NAMES[key] ?? STRATEGY_DISPLAY_NAMES[id]
  const lockSuffix = locked ? '（会员）' : ''
  const archLabel = archetype ? STRATEGY_ARCHETYPE_LABEL[archetype] : undefined
  const archSuffix = archLabel ? ` · [${archLabel}]` : ''
  if (title) return `${id} · ${title}${archSuffix}${lockSuffix}`
  if (className) return `${id} · ${className}${archSuffix}${lockSuffix}`
  return `${id}${archSuffix}${lockSuffix}`
}
